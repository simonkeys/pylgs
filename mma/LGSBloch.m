        nVars, DMVariables[atomicSystem], B1, Fl1, A11NoVCC, A12VCC, A21Recoil, totalPopulationOperator, levelPopulationOperator, groundLevelPopulationOperator, excitedLevelPopulationOperator, inputParameters, 
