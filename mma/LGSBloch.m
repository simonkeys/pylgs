			Export[FileNameJoin[{dir, "LevelDiagramNotToScale.svg"}], lgs["LevelDiagramNotToScale"]]
			Export[FileNameJoin[{dir, "info.md"}], LGSSystemInfo[lgs], "Text"]
		}
	]
]


